const formularioNtp = document.getElementById('adapta-pe-ntp-busqueda');
const consultaNtp = document.getElementById('adapta-pe-ntp-consulta');
const avisoNtp = document.getElementById('adapta-pe-ntp-aviso');

// chrome.search respeta el buscador predeterminado elegido por la persona.
formularioNtp.addEventListener('submit', evento => {
    evento.preventDefault();
    const texto = consultaNtp.value.trim();
    if (!texto) { consultaNtp.focus(); return; }
    chrome.search.query({ text: texto, disposition: 'CURRENT_TAB' }).catch(() => ponerTexto(avisoNtp, 'ntp.noBusco'));
});
document.getElementById('adapta-pe-ntp-ia').addEventListener('click', () => {
    location.assign('https://www.google.com/search?udm=50&q=' + encodeURIComponent(consultaNtp.value.trim()));
});
// El reconocedor central (voz/escucha.js) reinicia en 300 ms–5 s tras cada fin: otro
// SpeechRecognition en esta página competiría por el micrófono. Se indica la orden por voz.
document.getElementById('adapta-pe-ntp-voz').addEventListener('click', async () => {
    let activa = false;
    try { activa = Boolean((await chrome.storage.local.get('voz')).voz); } catch (_) {}
    ponerTexto(avisoNtp, activa ? 'ntp.pistaVoz' : 'ntp.vozApagada');
    consultaNtp.focus();
});

function enlaceNtp(url, titulo, clase, iconoPropio) {
    const enlace = document.createElement('a');
    enlace.className = clase;
    enlace.href = url;
    const icono = document.createElement('img');
    icono.alt = '';
    icono.width = icono.height = 32;
    icono.src = iconoPropio || chrome.runtime.getURL('_favicon/') + '?size=32&pageUrl=' + encodeURIComponent(url);
    const nombre = document.createElement('span');
    nombre.textContent = titulo || new URL(url).hostname;
    enlace.append(icono, nombre);
    const elemento = document.createElement('li');
    elemento.append(enlace);
    return elemento;
}
const esWeb = url => /^https?:/.test(url || '');
function mostrarLista(idLista, idVacio, enlaces) {
    document.getElementById(idLista).replaceChildren(...enlaces);
    document.getElementById(idVacio).hidden = enlaces.length > 0;
}
