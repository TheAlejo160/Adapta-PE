// Serializar evita que dos cambios rápidos se pisen al leer y escribir el objeto completo.
let guardadoNtp = Promise.resolve();
function guardarTemaNtp(cambios) {
    guardadoNtp = guardadoNtp.catch(() => {}).then(async () => {
        const clave = TemaNuevaPestana.clave;
        const actual = TemaNuevaPestana.normalizar((await chrome.storage.local.get(clave))[clave]);
        await chrome.storage.local.set({ [clave]: { ...actual, ...cambios } });
    });
    return guardadoNtp.catch(error => { ponerTexto(estadoPanelNtp, 'ntp.noGuardo'); throw error; });
}
panelNtp.addEventListener('change', evento => {
    if (evento.target.name === 'adapta-pe-ntp-tema') guardarTemaNtp({ preset: evento.target.value }).catch(() => {});
});
acentoNtp.addEventListener('change', () => guardarTemaNtp({ acento: acentoNtp.value }).catch(() => {}));
document.getElementById('adapta-pe-ntp-acento-tema').addEventListener('click', () => guardarTemaNtp({ acento: null }).catch(() => {}));

// Reducir a 1920 px y JPEG de hasta 750 kB: ~1 MB en base64, dentro de la cuota de storage.local.
const ladoMaximoFondo = 1920, bytesMaximosFondo = 750000;
async function prepararFondoNtp(archivo) {
    if (!/^image\//.test(archivo.type)) throw new Error('Tipo no admitido');
    const imagen = await createImageBitmap(archivo);
    const escala = Math.min(1, ladoMaximoFondo / Math.max(imagen.width, imagen.height));
    const lienzo = document.createElement('canvas');
    lienzo.width = Math.max(1, Math.round(imagen.width * escala));
    lienzo.height = Math.max(1, Math.round(imagen.height * escala));
    const contexto = lienzo.getContext('2d');
    contexto.fillStyle = '#ffffff'; // JPEG no tiene transparencia.
    contexto.fillRect(0, 0, lienzo.width, lienzo.height);
    contexto.drawImage(imagen, 0, 0, lienzo.width, lienzo.height);
    imagen.close();
    for (const calidad of [0.82, 0.7, 0.58, 0.46, 0.34]) {
        const blob = await new Promise(resolver => lienzo.toBlob(resolver, 'image/jpeg', calidad));
        if (blob && blob.size <= bytesMaximosFondo) {
            return new Promise((resolver, rechazar) => {
                const lector = new FileReader();
                lector.onload = () => resolver(lector.result);
                lector.onerror = () => rechazar(lector.error);
                lector.readAsDataURL(blob);
            });
        }
    }
    throw new Error('Imagen demasiado grande');
}
// Chrome sólo abre el selector con activación real: teclado o ratón; el clic sintético de cámara o voz no basta.
document.getElementById('adapta-pe-ntp-elegir-fondo').addEventListener('click', () => archivoNtp.click());
archivoNtp.addEventListener('change', async () => {
    const [archivo] = archivoNtp.files;
    archivoNtp.value = '';
    if (!archivo) return;
    ponerTexto(estadoPanelNtp, 'ntp.preparandoFondo');
    let fondo;
    try { fondo = await prepararFondoNtp(archivo); } catch (_) { ponerTexto(estadoPanelNtp, 'ntp.fondoInvalido'); return; }
    guardarTemaNtp({ fondo }).then(() => ponerTexto(estadoPanelNtp, 'ntp.fondoGuardado'), () => {});
});
quitarFondoNtp.addEventListener('click', () => {
    guardarTemaNtp({ fondo: null }).then(() => {
        ponerTexto(estadoPanelNtp, 'ntp.fondoQuitado');
        document.getElementById('adapta-pe-ntp-elegir-fondo').focus(); // Quitar queda deshabilitado.
    }, () => {});
});
