// Chrome publica sus idiomas preferidos; no se inspecciona el sistema ni se solicitan permisos.
function idiomaPagina(guardado) {
    return CodigosVoz.includes(guardado) ? guardado
        : detectarIdiomaVoz([...(navigator.languages || []), navigator.language, chrome.i18n.getUILanguage()]);
}
// Texto fijo de una clave: traducirDocumento() lo vuelve a traducir al cambiar de idioma.
function ponerTexto(elemento, clave) {
    elemento.dataset.i18n = clave;
    const texto = TextosAdapta.t(clave, variablesPagina());
    if (elemento.textContent !== texto) elemento.textContent = texto; // Evita repetir avisos de role=status.
}
// Nombre de activación (`nombreActivacion`) que las pistas muestran como {palabra}.
let nombreActivacionPagina, idiomaGuardadoPagina;
function variablesPagina() { return { palabra: palabraActivacion(nombreActivacionPagina, TextosAdapta.idioma) }; }
// Traduce la página y avisa con `adapta-pe-idioma` para que cada script rehaga sus textos con variables.
function aplicarIdiomaPagina(guardado) {
    idiomaGuardadoPagina = guardado;
    TextosAdapta.fijarIdioma(idiomaPagina(guardado));
    TextosAdapta.traducirDocumento(document, variablesPagina());
    // textos.js no traduce el atributo label de <optgroup>.
    for (const grupo of document.querySelectorAll('[data-i18n-label]')) grupo.label = TextosAdapta.t(grupo.dataset.i18nLabel);
    document.dispatchEvent(new Event('adapta-pe-idioma'));
}
aplicarIdiomaPagina(); // Idioma del sistema sin esperar a storage: «auto» es el caso habitual.
let revisionIdiomaPagina = 0, revisionNombrePagina = 0;
chrome.storage.local.get(['idiomaVoz', 'nombreActivacion']).then(res => {
    if (!revisionNombrePagina) nombreActivacionPagina = res.nombreActivacion;
    if (!revisionIdiomaPagina) aplicarIdiomaPagina(res.idiomaVoz);
    else if (!revisionNombrePagina) aplicarIdiomaPagina(idiomaGuardadoPagina);
}).catch(() => {});
chrome.storage.onChanged.addListener((cambios, area) => {
    if (area !== 'local' || !(cambios.idiomaVoz || cambios.nombreActivacion)) return;
    if (cambios.nombreActivacion) { revisionNombrePagina++; nombreActivacionPagina = cambios.nombreActivacion.newValue; }
    if (cambios.idiomaVoz) { revisionIdiomaPagina++; idiomaGuardadoPagina = cambios.idiomaVoz.newValue; }
    aplicarIdiomaPagina(idiomaGuardadoPagina);
});
